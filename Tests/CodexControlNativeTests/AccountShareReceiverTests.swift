    func testPairLostResponseRetryRestartRefreshAndLocalAccountIsolation() async throws {
        let suite = "AccountShareReceiverTests.\(UUID())"
        let defaults = UserDefaults(suiteName: suite)!
        defer { defaults.removePersistentDomain(forName: suite) }
        var vault: [String: Data] = [:]
        let config = URLSessionConfiguration.ephemeral; config.protocolClasses = [AccountReceiverProtocol.self]
        let session = URLSession(configuration: config); defer { session.invalidateAndCancel(); AccountReceiverProtocol.handler = nil }
        let key = Data(0..<32), id = UUID().uuidString.lowercased()
        let proof = key.base64EncodedString().replacingOccurrences(of: "=", with: "")
        let access = SharedAccountAccess(accessToken: "synthetic-only", chatgptAccountId: "same-account", chatgptPlanType: "plus", email: "fixture@example.invalid", expiresAt: Date().timeIntervalSince1970 + 1800)
        var version: Int64 = 1, claims = 0, reads = 0, lost = true
        var receiverProof: String?
        AccountReceiverProtocol.handler = { request in
            XCTAssertEqual(request.url?.path.hasPrefix("/ai/api/cloud-codex/account-shares/"), true)
            let received = request.value(forHTTPHeaderField: "X-CloudCodex-Share-Token")
            if let receiverProof { XCTAssertEqual(received, receiverProof) } else { receiverProof = received }
            if request.url!.path.hasSuffix("/claim") {
                claims += 1
                if lost { lost = false; throw URLError(.networkConnectionLost) }
            } else if request.url!.path.hasSuffix("/refresh") { version += 1; return Data("{\"status\":0}".utf8) }
            else { reads += 1 }
            let cipher = try AccountShareCrypto.seal(access, id: id, version: version, key: key)
            return try JSONSerialization.data(withJSONObject: ["status": 0, "data": ["id": id, "version": version, "ciphertext": cipher]])
        }
        func make() -> AccountShareReceiver {
            AccountShareReceiver(defaults: defaults, session: session,
                load: { id in try XCTUnwrap(vault[id]) }, save: { vault[$1] = $0 }, delete: { vault[$0] = nil })
        }
        let receiver = make()
        do { _ = try await receiver.pair(code: "CCS1.\(id).\(proof).\(proof)", server: "https://relay.example.invalid/ai"); XCTFail("Lost response should fail") }
        catch { }
        let restored = make()
        let (accountID, paired) = try await restored.pair(code: "", server: "https://relay.example.invalid/ai")
        XCTAssertEqual(paired.chatgptAccountId, access.chatgptAccountId); XCTAssertEqual(claims, 2)
        restored.finishPairing()
        let fetched = try await make().access(accountID: accountID)
        XCTAssertEqual(fetched.accessToken, access.accessToken); XCTAssertEqual(claims, 2); XCTAssertEqual(reads, 1)
        let renewed = try await restored.access(accountID: accountID, refresh: true)
        XCTAssertEqual(renewed.chatgptAccountId, access.chatgptAccountId)
        XCTAssertFalse(String(decoding: try XCTUnwrap(vault[accountID]), as: UTF8.self).contains(access.accessToken))
        let root = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: root) }
        let store = CodexAccountStore(defaults: defaults, root: root)
        try store.addSharedAccount(id: accountID, access: paired)
        XCTAssertEqual(store.active.id, "local")
        let account = try XCTUnwrap(store.library.accounts.last); XCTAssertTrue(account.isShared)
        var removed = false; store.removeSharedBinding = { removed = $0 == accountID }
        await store.remove(account)
        XCTAssertTrue(removed); XCTAssertEqual(store.library.accounts.count, 1)
        XCTAssertFalse(FileManager.default.fileExists(atPath: root.appendingPathComponent(accountID).appendingPathComponent("auth.json").path))
    }
}
private final class AccountReceiverProtocol: URLProtocol {
    static var handler: ((URLRequest) throws -> Data)?
    override class func canInit(with request: URLRequest) -> Bool { true }
    override class func canonicalRequest(for request: URLRequest) -> URLRequest { request }
    override func startLoading() {
        do {
            let data = try Self.handler!(request)
            client?.urlProtocol(self, didReceive: HTTPURLResponse(url: request.url!, statusCode: 200, httpVersion: nil, headerFields: nil)!, cacheStoragePolicy: .notAllowed)
            client?.urlProtocol(self, didLoad: data); client?.urlProtocolDidFinishLoading(self)
        } catch { client?.urlProtocol(self, didFailWithError: error) }
    }
    override func stopLoading() { }
}
